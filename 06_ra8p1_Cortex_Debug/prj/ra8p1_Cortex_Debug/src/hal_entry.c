#define SAMPLE_RATE_HZ       100   // 每10ms输出一次 = 100Hz采样率
#define SIGNAL_FREQ_HZ       16000 // 16kHz正弦波
#define PI                   3.14159265358979323846

// 全局变量：当前相位（弧度）
static float phase = 0.0f;
// 每次采样的相位增量：2 * PI * (信号频率 / 采样率)
static const float phase_increment = 2.0f * PI * (SIGNAL_FREQ_HZ / SAMPLE_RATE_HZ);

void rtt_send_float(float val) {
    uint8_t buf[5];
    buf[0] = 0x07;              // type_byte = float
    memcpy(&buf[1], &val, 4);   // 小端序4字节
    SEGGER_RTT_Write(1, buf, 5); // 通道1
}

// 如果选了固定格式"float (4字节)"，则不需要type_byte：
void rtt_send_float_fixed(float val) {
    int written = SEGGER_RTT_Write(1, &val, 4); // 直接发4字节
    if (written != 4) {
            SEGGER_RTT_printf(0, "Channel 1 write failed, written=%d\r\n", written);
    }
    SEGGER_RTT_printf(0, "Channel 0 test\n");
}

// 定时器中断回调（每10ms调用一次）
void on_10ms_timer(void) {
    // 计算正弦值，范围 -1.0 到 1.0
    float sin_value = sinf(phase);
    // 将正弦波映射到输出电压范围，例如 0~3.3V
    float output_voltage = 1.65f + 1.65f * sin_value; // 中心点1.65V，幅度1.65V
    rtt_send_float_fixed(output_voltage);


    // 更新相位，并限制在 0~2PI 范围内（防止累积误差）
    phase += phase_increment;
    if (phase >= 2.0f * PI) {
        phase -= 2.0f * PI;
    }
}

