volatile uint32_t global_hw_tick = 0;

#pragma pack(push, 1)
typedef struct {
    uint32_t hw_timestamp; // t4: 硬件时间戳，例如来自一个1MHz的自由运行计数器
    uint32_t value;        // u4: 采样值 (针对CH1)
} JScopePacket_u4;

typedef struct {
    uint32_t hw_timestamp; // t4: 硬件时间戳
    uint8_t  value;        // u1: 采样值 (针对CH2)
} JScopePacket_u1;
#pragma pack(pop)

static volatile uint32_t temp1 = 0;
static volatile uint32_t temp2 = 0;
void g_gpt0CB(timer_callback_args_t *p_args)
{
    if(p_args->event == TIMER_EVENT_CYCLE_END)
    {
#if RTT_TIMESTAMP
        uint32_t now_tick = global_hw_tick;

        // 准备并发送CH1数据
        JScopePacket_u4 pkt1;
        pkt1.hw_timestamp = now_tick;
        pkt1.value = (temp1 == 100) ? 0 : 100;
        SEGGER_RTT_Write(1, &pkt1, sizeof(pkt1));

        // 准备并发送CH2数据
        JScopePacket_u1 pkt2;
        pkt2.hw_timestamp = now_tick;
        pkt2.value = (temp2 == 90) ? 10 : 90;
        SEGGER_RTT_Write(2, &pkt2, sizeof(pkt2));

        temp1 = pkt1.value;
        temp2 = pkt2.value;
#else
//        temp1 = (temp1 == 100) ? 0 : 100;
//        SEGGER_RTT_Write(1, &temp1, 4); // 通道1
//
//        temp2 = (temp2 == 90) ? 10 : 90;
//        SEGGER_RTT_Write(2, &temp2, 1); // 通道2

        // 一个通道,一次发送所有数据
#pragma pack(push, 1)  // 开始1字节对齐
        typedef struct {
            uint32_t ch1;
            uint32_t ch2;
            // 可以扩展更多通道
        } MultiChannelData_t;
#pragma pack(pop)       // 恢复默认对齐

        MultiChannelData_t data;

        temp1 = (temp1 == 100) ? 0 : 100;
        temp2 = (temp2 == 90) ? 10 : 90;
        data.ch1 = temp1;
        data.ch2 = temp2;
        SEGGER_RTT_Write(1, &data, sizeof(data));
#endif
    }
}

